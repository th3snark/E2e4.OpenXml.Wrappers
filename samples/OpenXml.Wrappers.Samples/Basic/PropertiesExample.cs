using System.Globalization;

using OpenXml.Wrappers.Word;

namespace OpenXml.Wrappers.Samples.Basic;

/// <summary>
/// Document properties: the built-in ones (title, author...) that Word shows under File, Info, and custom ones of your own.
/// </summary>
internal static class PropertiesExample
{
    public static void Create(string path)
    {
        using (WordprocessingDocumentWrapper document = WordprocessingDocumentWrapper.Create(path, true, false))
        {
            DocumentPropertiesWrapper properties = document.BuiltInDocumentProperties;
            properties.Title = "Project Apollo status";
            properties.Subject = "Monthly status report";
            properties.Author = "Ana Silva";
            properties.Keywords = "status; apollo; report";
            properties.Comments = "Generated by the properties example.";
            properties.Category = "Reports";
            properties.Company = "Example Ltd";
            properties.Manager = "Ben Okafor";
            properties.CreationDate = new DateTime(2026, 3, 1, 8, 0, 0, DateTimeKind.Utc);

            //Custom properties have a name, a type and a value. Names are not case sensitive.
            CustomDocumentPropertyCollection custom = document.CustomDocumentProperties;
            custom.Add("Project code", DocumentPropertyType.Text, "APOLLO-7");
            custom.Add("Revision", DocumentPropertyType.Number, 3);
            custom.Add("Budget used", DocumentPropertyType.FloatingPoint, 0.42);
            custom.Add("Approved", DocumentPropertyType.Boolean, false);
            custom.Add("Review date", DocumentPropertyType.Date, new DateTime(2026, 4, 1, 0, 0, 0, DateTimeKind.Utc));

            //Values are read back with the type they were stored with, and can be changed.
            custom["revision"].Value = (int)custom["revision"].Value + 1;
            custom["Approved"].Value = true;

            document.Paragraphs[0].Range.Text = "The properties of this document are under File, Info, Properties in Word.";
            document.Paragraphs.Add().Range.Text = string.Format(CultureInfo.InvariantCulture, "Title: {0}. Author: {1}.", properties.Title, properties.Author);
            document.Paragraphs.Add().Range.Text = "Custom properties: " + string.Join("; ", custom.Select(p => p.Name + " = " + Convert.ToString(p.Value, CultureInfo.InvariantCulture)));
        }
    }
}
